B.redo = B.undo.map((r) => [...r].reverse().join(''));

export function icon(name, px = 2) {
  const rows = B[name];
  if (!rows) return '';
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '#') rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
      else if (ch === 'o') rects += `<rect x="${x}" y="${y}" width="1" height="1" opacity=".45"/>`;
    }
  });
  const s = 10 * px;
  return `<svg class="ico" width="${s}" height="${s}" viewBox="0 0 10 10" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}
